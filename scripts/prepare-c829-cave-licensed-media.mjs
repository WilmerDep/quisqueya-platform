/**
 * C8.29-F — Prepare three rights-cleared Cueva de las Maravillas photographs.
 * Local files only; NO Google Drive/MySQL/API writes. Uses Wikimedia Commons MediaWiki API.
 * Run: node scripts/prepare-c829-cave-licensed-media.mjs
 * Returns metadata with attribution/licence and downloaded optimized (1600px) JPEGs.
 */
import { mkdir, writeFile, readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { createHash } from "node:crypto";

const target=resolve("local-media-c829-cave");
const files=[
  {title:"File:Cuevas de las Maravillas.jpg",slug:"cueva-de-las-maravillas-interior-01.jpg"},
  {title:"File:Taíno pictographs Cuevas de las Maravillas.jpg",slug:"cueva-de-las-maravillas-pictografias-tainas-01.jpg"},
  {title:"File:Taíno pictographs Cuevas de las Maravillas 2.jpg",slug:"cueva-de-las-maravillas-pictografias-tainas-02.jpg"}
];
// Thumb URLs returned by the Commons API can contain cache/version query strings.
// A query is not a new network destination: restrict the host and path, not the presence of a query.
const allowedThumbnailUrl=u=>u.protocol==="https:" &&
  !u.username && !u.password && !u.hash &&
  ((u.hostname==="thumb.wikimedia.org" && u.pathname.startsWith("/wikipedia/commons/thumb/")) ||
   (u.hostname==="upload.wikimedia.org" && u.pathname.startsWith("/wikipedia/commons/"))) &&
  /\.(?:jpe?g)$/i.test(u.pathname);
const urlFor=(title)=>{
  const u=new URL("https://commons.wikimedia.org/w/api.php");
  u.searchParams.set("action","query");
  u.searchParams.set("format","json");
  u.searchParams.set("prop","imageinfo");
  u.searchParams.set("titles",title);
  u.searchParams.set("iiprop","url|extmetadata|size");
  u.searchParams.set("iiurlwidth","1600");
  return u;
};
const log=(k,v)=>console.log(k+"="+JSON.stringify(v));
const prepared=[];
try{
  for(const x of files){
    const response=await fetch(urlFor(x.title),{headers:{"User-Agent":"QuisqueyaMediaPreparation/1.0 (local metadata fetch)"},signal:AbortSignal.timeout(25000)});
    if(!response.ok)throw new Error("COMMONS_METADATA_HTTP_"+response.status);
    const json=await response.json();
    const info=Object.values(json?.query?.pages||{})[0]?.imageinfo?.[0];
    const license=String(info?.extmetadata?.LicenseShortName?.value||"");
    const artist=String(info?.extmetadata?.Artist?.value||"");
    if(!/^CC BY-SA 4\.0$/i.test(license) || !/Danu Widjajanto/i.test(artist))
      throw new Error("LICENSE_OR_AUTHOR_NOT_VERIFIED_"+x.slug);
    const download=info.thumburl;
    const u=new URL(download);
    if(!allowedThumbnailUrl(u)){
      console.log("C8_29_F_HOST_DIAGNOSTIC="+JSON.stringify({file:x.slug,hostname:u.hostname,protocol:u.protocol,pathnamePrefix:u.pathname.split("/").slice(0,4).join("/"),queryPresent:Boolean(u.search),extension:u.pathname.split(".").at(-1)}));
      throw new Error("UNTRUSTED_DOWNLOAD_HOST");
    }
    const img=await fetch(download,{redirect:"error",signal:AbortSignal.timeout(30000)});
    if(!img.ok||!String(img.headers.get("content-type")||"").startsWith("image/jpeg"))
      throw new Error("INVALID_IMAGE_RESPONSE_"+x.slug);
    const bytes=Buffer.from(await img.arrayBuffer());
    if(bytes.length<15_000||bytes.length>8_000_000||bytes[0]!==0xff||bytes[1]!==0xd8)
      throw new Error("INVALID_JPEG_"+x.slug);
    prepared.push({
      fileName:x.slug,bytes,
      metadata:{
        fileName:x.slug,
        originalTitle:x.title,
        pageUrl:String(info.descriptionurl),
        sourceUrl:String(info.url),
        creator:"Danu Widjajanto",
        license:"CC BY-SA 4.0",
        licenseUrl:"https://creativecommons.org/licenses/by-sa/4.0/",
        changes:"Scaled derivative generated by Wikimedia thumbnail service (1600px maximum width); no additional edits.",
        mimeType:"image/jpeg",
        sizeBytes:bytes.length,
        sha256:createHash("sha256").update(bytes).digest("hex"),
        editorialStatus:"PROVISIONAL_CANDIDATE",
        destinationFolder:"PAGINA WEB/Experiencias/Cueva de las Maravillas",
      }
    });
  }
  await mkdir(target,{recursive:true});
  for(const x of prepared)await writeFile(resolve(target,x.fileName),x.bytes,{flag:"w"});
  const manifest={schemaVersion:1,cycle:"C8.29-F",
    scope:"LOCAL_IMAGE_PREPARATION_ONLY",
    creditsStatement:"Photographs © Danu Widjajanto; licensed under CC BY-SA 4.0. Originals linked per image; derivative versions scaled by Wikimedia. Appropriate attribution and ShareAlike terms apply to adaptations.",
    assets:prepared.map(x=>x.metadata)};
  await writeFile(resolve(target,"attribution-manifest.json"),JSON.stringify(manifest,null,2)+"\n");
  log("C8_29_F_ASSETS",prepared.map(x=>({fileName:x.fileName,bytes:x.metadata.sizeBytes,license:x.metadata.license,sha256:x.metadata.sha256})));
  log("C8_29_F_OUTPUT",target);
  console.log("C8_29_F=LOCAL_FILES_PREPARED");
}catch(e){
  console.log("C8_29_F=REVIEW_REQUIRED");
  console.log("ERROR_CODE="+String(e?.message||e?.name||"UNKNOWN"));
  process.exitCode=2;
}finally{
  console.log("DRIVE=NOT_MODIFIED");
  console.log("MYSQL=NOT_MODIFIED");
  console.log("STAGING=NOT_MODIFIED");
  console.log("PRODUCTION=NOT_MODIFIED");
}
